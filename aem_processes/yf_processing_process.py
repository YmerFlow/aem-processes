"""Processing and QC of AEM data with ymerflow-processing pipelines.

Two process types over one library:

* ``yf_process_tem`` runs a processing pipeline: dataset in, processed dataset out.
* ``yf_qc_tem`` runs a QC pipeline: the same dataset out with verdict columns.

Both write the library's run report as ``report.json`` beside the output
dataset, listed in its info.json. The steps form is generated by swaggerspect
from the steps the library registers under its entry-point groups, so a step
contributed by any installed package appears without changes here, and it
opens with the library's bundled pipeline filled in.
"""

import contextlib
import functools
import inspect
import json
import logging
import os
import sys
import tempfile
import typing

import fsspec
import swaggerspect

from .dataset_utils import write_dataset
from .utils import localize_urls

XYZ_MIME = "text/x-aarhusxyz"
GEX_MIME = "text/x-aarhusxyz-gex"
MSGPACK_MIME = "application/x-aarhusxyz-msgpack"
REPORT_MIME = "application/vnd.ymerflow.run-report+json"

# ── The steps form ───────────────────────────────────────────────────────────

def steps_schema(group, bundled):
    """The steps form: every step registered under ``group``, prefilled with ``bundled``.

    swaggerspect builds one form per step from the library's entry points, with
    each parameter's type, default and description from the step's NumPy
    docstring. Every step's first parameter is the dataset, which the process
    supplies, so it is taken out of each form. Steps are offered in the order
    the bundled pipeline uses them, then the rest alphabetically. Without the
    library installed the form is a bare list, so a package missing from an
    environment shows up as a form rather than a failed build.
    """
    try:
        from ymerflow_processing.pipeline import Pipeline
    except ImportError:
        print("ymerflow-processing is not installed; the steps form is a bare list")
        return {"type": "array", "title": "Steps",
                "description": "Pipeline steps, each a mapping of step name to its parameters",
                "items": {"type": "object"}}

    steps = swaggerspect.get_apis(group, multi=True)
    pipeline = Pipeline.load(bundled)
    by_name = {next(iter(api["properties"])): api for api in steps["items"]["anyOf"]}
    for name, api in by_name.items():
        arguments = api["properties"][name]
        arguments.get("properties", {}).pop("dataset", None)
        for listing in ("propertyOrder", "required"):
            if "dataset" in arguments.get(listing, []):
                arguments[listing] = [p for p in arguments[listing] if p != "dataset"]
        # A field offering a choice of types must not also demand one. swaggerspect
        # adds the docstring's type text, which it reads as "object", beside the
        # anyOf from the signature, and then no number validates.
        for field in arguments.get("properties", {}).values():
            if "anyOf" in field:
                field.pop("type", None)
    order = list(dict.fromkeys([name for name, _ in pipeline.steps if name in by_name]
                               + sorted(by_name)))
    steps["items"]["anyOf"] = [by_name[name] for name in order]
    steps.update(title="Steps",
                 description=f"Applied in order. Opens with the bundled {bundled} pipeline.",
                 minItems=1,
                 default=[{name: params} for name, params in pipeline.steps])
    return steps


# ── Running ──────────────────────────────────────────────────────────────────

@contextlib.contextmanager
def _local_files(input_data, storage_kwargs):
    """The input dataset's XYZ and GEX as local paths, and the dataset's name.

    The library reads two files and never touches storage, so they are fetched
    here. A dataset written before the text forms existed is converted from its
    msgpack.
    """
    prefix = input_data.rsplit("/", 1)[0]
    with fsspec.open(f"{prefix}/info.json", "r", **storage_kwargs) as f:
        info = json.load(f)
    files = info.get("files", {})
    name = info.get("dataset_name")

    if XYZ_MIME in files and GEX_MIME in files:
        with localize_urls({"xyz": files[XYZ_MIME], "gex": files[GEX_MIME]}, storage_kwargs) as local:
            yield local["xyz"], local["gex"], name
        return

    from libaarhusxyz.export import msgpack as xyz_msgpack
    with localize_urls({"msgpack": files.get(MSGPACK_MIME, input_data)}, storage_kwargs) as local, \
            tempfile.TemporaryDirectory() as directory:
        xyz, gex = xyz_msgpack.load(local["msgpack"], return_gex=True)
        if gex is None:
            raise ValueError("The input dataset carries no system description (GEX)")
        xyz_path = os.path.join(directory, "root.xyz")
        gex_path = os.path.join(directory, "root.gex")
        xyz.dump(xyz_path)
        with open(gex_path, "wb") as f:
            gex.dump(f)
        yield xyz_path, gex_path, name


@contextlib.contextmanager
def _library_log_to_stdout():
    """Stream the library's log lines into the process log as they happen."""
    handler = logging.StreamHandler(sys.stdout)
    handler.setFormatter(logging.Formatter("%(levelname)s %(name)s: %(message)s"))
    log = logging.getLogger("ymerflow_processing")
    level = log.level
    log.addHandler(handler)
    log.setLevel(logging.INFO)
    try:
        yield
    finally:
        log.removeHandler(handler)
        log.setLevel(level)


def _summarize(report, dataset):
    """What the run found, printed for the log, and returned for the report.

    A finding is not a failure: an out-of-spec or ungraded result completes the
    process normally and is said here. Only a step that raises fails it.
    """
    from ymerflow_processing.pipeline import MISSING
    from ymerflow_processing.qc.thresholds import GOOD, worst_verdict

    for step in report.steps:
        counts = step.distributions.get("verdicts")
        line = f"  {step.step}"
        if counts:
            line += ": " + ", ".join(f"{n} {tier}" for tier, n in counts.items() if n)
        print(line)
        for note in step.notes:
            print(f"    note: {note}")

    def worst(column):
        frame = dataset.flightlines
        if frame is None or not column or column not in frame.columns:
            return None
        return worst_verdict(frame[[column]])

    columns = report.rollup.get("columns", {})
    flight = worst(columns.get("verdict"))
    instrument = worst(columns.get("sensor"))
    ungraded = [step.step for step in report.steps if step.ungraded == MISSING]

    if ungraded:
        print(f"{len(ungraded)} check(s) found no input and produced no verdict: "
              f"{', '.join(ungraded)}. The flight is UNGRADED, not clean.")
    if flight is not None:
        print(f"worst verdict: {flight}")
    if instrument is not None and instrument != GOOD:
        print(f"instrument: {instrument}. An equipment fault, not a flying problem; "
              f"the data may still be usable.")
    return {"worst_verdict": flight, "instrument": instrument, "ungraded": ungraded}


def data_parameters(step):
    """The parameters of a step that read data from where a string points.

    The library types its external inputs: a parameter that takes a loaded
    object as well as a string (``str | XYZ``, ``str | GeoDataFrame``, ``str |
    rasterio.DatasetReader``) reads data, and a string given to it says where
    from. Every other string is a value — an output path, a column name, a
    method — so ``str | dict`` does not count (``dict`` is built in, not data),
    nor does ``str | Path``.

    Parameters
    ----------
    step : callable
        A registered step function.

    Returns
    -------
    list of str
        The names of its data parameters, in signature order.
    """
    names = []
    for name, parameter in inspect.signature(step, eval_str=True).parameters.items():
        members = typing.get_args(parameter.annotation) or (parameter.annotation,)
        loaded = [m for m in members if isinstance(m, type) and m.__module__ != "builtins"
                  and not issubclass(m, os.PathLike)]
        if str in members and loaded:
            names.append(name)
    return names


def _reading_local_copies(step, parameters, local):
    """``step``, called with the local copy wherever one of ``parameters`` names a fetched URL."""
    @functools.wraps(step)
    def run_step(dataset, **params):
        params = {key: local.get(value, value) if key in parameters and isinstance(value, str) else value
                  for key, value in params.items()}
        return step(dataset, **params)
    return run_step


def fetch_step_inputs(pipeline, registered, storage_kwargs, held):
    """The registry to run with, its steps reading local copies of the data they name.

    The library opens only local paths, so a URL given to a data parameter
    (:func:`data_parameters`) is downloaded here, before the run starts, and the
    copy is kept until ``held`` closes. Only the step's call sees the copy: the
    pipeline keeps the URL, and the runner records the pipeline's parameters, so
    the report and the dataset's processing history name where the data came
    from, not a temporary file. Any other parameter is passed as given, so an
    output location in storage is never read as an input.

    Parameters
    ----------
    pipeline : ymerflow_processing.pipeline.Pipeline
        The pipeline to run, already validated against ``registered``.
    registered : dict
        Step name to step function, from the library's registry.
    storage_kwargs : dict
        fsspec options for the project's storage.
    held : contextlib.ExitStack
        Holds the downloaded copies; closing it deletes them.

    Returns
    -------
    dict
        ``registered`` itself when no step is given a URL as data, otherwise a
        copy in which those steps read the local copies.
    """
    wanted, urls = {}, set()
    for name, params in pipeline.steps:
        parameters = data_parameters(registered[name])
        given = {value for key, value in params.items()
                 if key in parameters and isinstance(value, str) and "://" in value}
        if given:
            wanted[name] = parameters
            urls |= given
    if not urls:
        return registered

    print(f"Fetching step inputs: {', '.join(sorted(urls))}")
    local = held.enter_context(localize_urls({url: url for url in urls}, storage_kwargs))
    steps = dict(registered)
    for name, parameters in wanted.items():
        steps[name] = _reading_local_copies(registered[name], parameters, local)
    return steps


#: What a saved edit is a difference from: this process's output before it.
EDIT_CHECKPOINT = "output of the steps above"


def _replay_edits(dataset, diff, registered, report, storage_kwargs):
    """Apply one save's in-use edits, after every step.

    Last, so that no automated step can overwrite a person's decision; called
    once per save, oldest first, so a later save overrides an earlier one where
    both touched the same gate. Run here rather than appended to the pipeline so
    the report and the dataset's processing history record the edits' URL, not
    a temporary file.
    """
    params = {"diff": diff, "checkpoint": EDIT_CHECKPOINT}
    with localize_urls({"diff": diff}, storage_kwargs) as local:
        dataset, step_report = registered["apply_manual_edits"](
            dataset, local["diff"], checkpoint=EDIT_CHECKPOINT)
    step_report.params = params
    report.steps.append(step_report)
    report.pipeline["steps"] = list(report.pipeline["steps"]) + [{"apply_manual_edits": params}]
    dataset.record_step("apply_manual_edits", params)
    return dataset


class _PipelineProcess:
    """A ymerflow-processing pipeline run as a process type."""

    group = ""        # entry-point group the steps come from
    kind = ""         # the library's name for that group
    runner = ""       # the library's runner class for it
    bundled = ""      # bundled pipeline the form opens with
    output_name = ""  # name of the output dataset
    takes_edits = False  # whether in-use edits saved from a plot are replayed
    title = ""
    description = ""

    @classmethod
    def schema(cls):
        properties = {
            "input_data": {
                "type": "string",
                "format": "uri",
                "x-format": "dataset",
                "title": "Input Dataset",
                "description": "An imported or previously processed AEM dataset",
            },
            "steps": steps_schema(cls.group, cls.bundled),
            "label": {
                "type": "string",
                "title": "Run Label",
                "description": "What to call this run in its report. Defaults to the input dataset's name.",
            },
        }
        if cls.takes_edits:
            # The name the plot editor uses: saving edits creates a new version
            # of the process that made the dataset, with the new edits appended
            # to "diff". Each entry holds one save's changes.
            properties["diff"] = {
                "type": "array",
                "items": {"type": "string", "format": "uri"},
                "title": "Manual Edits",
                "description": "In-use edits saved from plots of this process's output, one entry "
                               "per save, oldest first. Filled in by the plot editor; replayed in "
                               "order after every step, so re-running keeps every round.",
            }
        return {
            "type": "object",
            "title": cls.title,
            "description": cls.description,
            "properties": properties,
            "required": ["input_data", "steps"],
        }

    @classmethod
    def run(cls, storage_context=None, **kwargs):
        print(f"Running {cls.title}...")
        print(f"Parameters: {kwargs}")

        if not storage_context:
            raise ValueError("storage_context is required")
        process_id = storage_context["process_id"]
        process_version = storage_context["version"]
        storage_base = storage_context["storage_base"]
        storage_kwargs = storage_context["storage_kwargs"]

        input_data = kwargs.get("input_data")
        steps = kwargs.get("steps") or []
        label = kwargs.get("label")
        # A list, oldest first; a single URL from a version saved before edits
        # accumulated is one round.
        diff = kwargs.get("diff") or []
        diffs = [diff] if isinstance(diff, str) else list(diff)
        if not input_data:
            raise ValueError("input_data is required")
        if not steps:
            raise ValueError("No steps given; a pipeline needs at least one")
        if diffs and not cls.takes_edits:
            raise ValueError(f"{cls.title} changes no data, so it takes no in-use edits. "
                             f"Save the edits on a processed dataset instead.")

        from ymerflow_processing import pipeline as yfp
        from ymerflow_processing.dataset import load

        # Checked before any data is fetched, so a misspelled step or a QC step
        # in a processing pipeline fails at once and says which registry it is in.
        pipeline = yfp.Pipeline({"kind": cls.kind, "steps": steps})
        _, registered = yfp.resolve_group(pipeline, ["filters", "qc"])
        pipeline.validate(registered)

        with contextlib.ExitStack() as held, _library_log_to_stdout():
            runner = getattr(yfp, cls.runner)(
                pipeline, fetch_step_inputs(pipeline, registered, storage_kwargs, held))
            with _local_files(input_data, storage_kwargs) as (xyz_path, gex_path, dataset_name):
                dataset = load(xyz_path, gex_path)
            report = yfp.RunReport(pipeline=pipeline.document,
                                   identity=label or dataset_name,
                                   identity_source="label" if label else "dataset",
                                   **dataset.describe())
            print(f"{report.identity}: {dataset.n_soundings} soundings, "
                  f"{len(pipeline.steps)} step(s) [{cls.kind}]")
            dataset, walked = runner.run(dataset)
            report.steps = walked.steps
            report.rollup = walked.rollup
            for url in diffs:
                dataset = _replay_edits(dataset, url, registered, report, storage_kwargs)
        summary = _summarize(report, dataset)

        # libaarhusxyz's text reader lowercases every name. Restore the spelling
        # the input declares (the importers' "alc"), so the output matches every
        # other dataset in the project and its own naming_standard.
        xyz = dataset.survey.xyz
        xyz.normalize_naming(naming_standard=xyz.model_info.get("naming_standard") or "alc")
        report_json = json.dumps(dict(report.to_dict(), summary=summary), indent=2, default=str)

        print(f"Writing {cls.output_name}...")
        dataset_id = write_dataset(
            dataset.survey.xyz,
            dataset.survey.gex,
            cls.output_name,
            process_id,
            process_version,
            storage_base,
            storage_kwargs,
            extra_files={REPORT_MIME: ("report.json", report_json)},
        )
        outputs = {
            cls.output_name: f"{storage_base}/processes/{process_id}/{process_version}/datasets/{dataset_id}/root.msgpack"
        }
        print(f"{cls.title} complete")
        return {"status": "success", "outputs": outputs}


class YFProcessTEM(_PipelineProcess):
    """Process AEM data with a ymerflow-processing pipeline."""

    group = "ymerflow.processing.filters"
    kind = "filters"
    runner = "ProcessingRunner"
    bundled = "standard-processing"
    output_name = "processed_data"
    takes_edits = True
    title = "Process TEM (ymerflow-processing)"
    description = ("Apply a ymerflow-processing pipeline to an AEM dataset: corrections, a noise "
                   "model, uncertainties, culling and averaging. Opens with the standard "
                   "processing chain; edit, add or remove steps. Writes the processed dataset "
                   "and a run report.")


class YFQCTEM(_PipelineProcess):
    """Grade AEM data against acquisition specification with a ymerflow-processing pipeline."""

    group = "ymerflow.processing.qc"
    kind = "qc"
    runner = "QCRunner"
    bundled = "acquisition-qc"
    output_name = "qc_data"
    title = "QC TEM (ymerflow-processing)"
    description = ("Grade an AEM dataset against acquisition specification: height, attitude, "
                   "speed, spacing, transmitter stability and more. Changes no measurement; "
                   "writes the dataset with a verdict column per check and a run report. "
                   "The thresholds are representative defaults, not contract values.")
